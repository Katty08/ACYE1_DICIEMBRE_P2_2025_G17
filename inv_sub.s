/* -----------------------------------------
 * inv_sub
 * r0 = puntero al estado (16 bytes)
 * ----------------------------------------- */
inv_sub:
    push {r4-r6, lr}

    ldr r1, =inv_sbox
    mov r2, #16              @ contador

loop:
    ldrb r3, [r0]            @ byte estado
    ldrb r4, [r1, r3]        @ inv_sbox[byte]
    strb r4, [r0], #1        @ escribir y avanzar
    subs r2, r2, #1
    bne loop

    pop {r4-r6, lr}
    bx lr
